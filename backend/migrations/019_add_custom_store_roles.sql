-- Custom store roles (added after the Gantt tasks). Replaces migration 016's fixed "worker" and
-- "manager" roles: each store has its own roles, each a name and a list of permissions, e.g. a
-- "Cashier", "Stocker", or "Buyer". Staff have users.role = 'staff', their store in
-- users.store_id, and their role there in users.store_role_id.
--
-- The permissions a role may list are in app/schemas/store_role.py (PERMISSIONS). They aren't
-- checked here, so adding one needs no migration; the API ignores any it doesn't know.
--
-- Every store starts with two roles it can rename or change, "Manager" (every permission) and
-- "Worker" (edit stock), added by a trigger so stores added by scripts get them too. Existing
-- managers and workers move onto them with the same access they had. Safe to run more than once.

CREATE TABLE IF NOT EXISTS store_roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id INTEGER NOT NULL REFERENCES store_locations (id) ON DELETE CASCADE,
    name VARCHAR(50) NOT NULL CHECK (btrim(name) <> ''),
    permissions TEXT[] NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- So users can reference (store_id, id), which keeps a person's role at their own store.
    CONSTRAINT store_roles_store_id_id_key UNIQUE (store_id, id)
);

-- One role per name at each store, ignoring case.
CREATE UNIQUE INDEX IF NOT EXISTS store_roles_store_name_key ON store_roles (store_id, lower(name));

-- Like every other table (migration 011): no direct access through Supabase's REST API.
ALTER TABLE store_roles ENABLE ROW LEVEL SECURITY;

-- The two starting roles. Keep Manager's list in step with PERMISSIONS in app/schemas/store_role.py.
CREATE OR REPLACE FUNCTION add_default_store_roles() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO store_roles (store_id, name, permissions) VALUES
        (NEW.id, 'Manager',
            ARRAY['edit_stock', 'view_staff', 'manage_staff', 'manage_roles', 'edit_store_info']),
        (NEW.id, 'Worker', ARRAY['edit_stock']);
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS store_locations_default_roles ON store_locations;
CREATE TRIGGER store_locations_default_roles
    AFTER INSERT ON store_locations
    FOR EACH ROW EXECUTE FUNCTION add_default_store_roles();

-- Stores that already exist, unless they have roles already (a second run).
INSERT INTO store_roles (store_id, name, permissions)
SELECT s.id, d.name, d.permissions
FROM store_locations AS s
CROSS JOIN (VALUES
    ('Manager', ARRAY['edit_stock', 'view_staff', 'manage_staff', 'manage_roles', 'edit_store_info']),
    ('Worker', ARRAY['edit_stock'])
) AS d (name, permissions)
WHERE NOT EXISTS (SELECT 1 FROM store_roles AS r WHERE r.store_id = s.id);

ALTER TABLE users ADD COLUMN IF NOT EXISTS store_role_id INTEGER;

-- Migration 016's rules, replaced below.
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_staff_have_a_store;

-- Managers and workers become staff with the matching starting role at their store.
UPDATE users AS u
SET role = 'staff', store_role_id = r.id
FROM store_roles AS r
WHERE u.role IN ('worker', 'manager')
  AND r.store_id = u.store_id
  AND r.name = CASE u.role WHEN 'manager' THEN 'Manager' ELSE 'Worker' END;

ALTER TABLE users
    ADD CONSTRAINT users_role_check CHECK (role IN ('user', 'staff', 'admin'));

-- Staff always have a store and a role there, and nobody else has either. Deleting a store first
-- turns its staff back into regular users (DELETE /admin/stores/{id}); deleting a role someone
-- still has is refused.
ALTER TABLE users
    ADD CONSTRAINT users_staff_have_a_store CHECK (
        (role = 'staff') = (store_id IS NOT NULL)
        AND (role = 'staff') = (store_role_id IS NOT NULL)
    );

ALTER TABLE users DROP CONSTRAINT IF EXISTS users_store_role_fkey;
ALTER TABLE users
    ADD CONSTRAINT users_store_role_fkey
    FOREIGN KEY (store_id, store_role_id) REFERENCES store_roles (store_id, id);

-- Counting a role's people, and refusing to delete a role someone has.
CREATE INDEX IF NOT EXISTS users_store_role_id_idx
    ON users (store_role_id) WHERE store_role_id IS NOT NULL;
