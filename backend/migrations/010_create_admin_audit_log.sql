-- Audit log of admin changes (T083): who changed what, and when. The API adds a row in the same
-- transaction as each admin change, so a change and its log entry are saved together or not at
-- all. The API only ever adds rows; nothing in the database stops someone with direct database
-- access from editing them. Safe to run more than once.
CREATE TABLE IF NOT EXISTS admin_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Who: the admin's account, and their email at the time. If the account is deleted later,
    -- admin_id is cleared but the email still says who it was.
    admin_id UUID REFERENCES users(id) ON DELETE SET NULL,
    admin_email TEXT,
    -- What: e.g. action 'product.update' on target_type 'product', target_id '7'. changes holds
    -- each changed field as {"field": {"from": old, "to": new}}, or what was created or deleted.
    action VARCHAR(50) NOT NULL,
    target_type VARCHAR(50) NOT NULL,
    target_id TEXT NOT NULL,
    changes JSONB NOT NULL DEFAULT '{}',
    -- When.
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- The log is read newest first, overall or for one admin or one target (e.g. product 7).
CREATE INDEX IF NOT EXISTS admin_audit_log_created_at_idx
ON admin_audit_log (created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS admin_audit_log_target_idx
ON admin_audit_log (target_type, target_id, created_at DESC);

CREATE INDEX IF NOT EXISTS admin_audit_log_admin_idx
ON admin_audit_log (admin_id, created_at DESC);

-- As with the other tables: Supabase exposes public tables through its REST API, so with row
-- level security on and no policies, only the backend can read or write the log.
ALTER TABLE admin_audit_log ENABLE ROW LEVEL SECURITY;
