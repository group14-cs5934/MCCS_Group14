-- Saved products, a shopping cart, and demo orders (added after the Gantt tasks). See
-- app/api/shopping.py. Each belongs to one signed-in user. Orders are a demo: no payment, no real
-- delivery, and placing one doesn't change stock. Safe to run more than once.

-- Products a user saved for later.
CREATE TABLE IF NOT EXISTS saved_products (
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    saved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, product_id)
);

-- What's in a user's cart, and how many of each.
CREATE TABLE IF NOT EXISTS cart_items (
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
    added_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, product_id)
);

-- Placed orders. The store's and products' names and prices are copied in, so an order still
-- reads right after a store or product is changed or deleted.
CREATE TABLE IF NOT EXISTS orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    store_id INTEGER REFERENCES store_locations (id) ON DELETE SET NULL,
    store_name VARCHAR(200) NOT NULL,
    fulfillment VARCHAR(10) NOT NULL CHECK (fulfillment IN ('pickup', 'delivery')),
    delivery_address VARCHAR(300),
    contact_name VARCHAR(100),
    status VARCHAR(20) NOT NULL DEFAULT 'placed' CHECK (status IN ('placed')),
    placed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK ((fulfillment = 'delivery') = (delivery_address IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS orders_user_placed_idx ON orders (user_id, placed_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id INTEGER REFERENCES products (id) ON DELETE SET NULL,
    product_name VARCHAR(200) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2)
);

CREATE INDEX IF NOT EXISTS order_items_order_idx ON order_items (order_id, id);

