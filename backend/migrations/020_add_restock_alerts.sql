-- The two new permissions (app/schemas/store_role.py): roles that could already do everything,
-- like each store's starting Manager, get them too, and so do new stores' Managers.
UPDATE store_roles
SET permissions = permissions || ARRAY['view_restock', 'request_restock']
WHERE permissions @> ARRAY['edit_stock', 'view_staff', 'manage_staff', 'manage_roles', 'edit_store_info']
  AND NOT permissions @> ARRAY['view_restock'];

CREATE OR REPLACE FUNCTION add_default_store_roles() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO store_roles (store_id, name, permissions) VALUES
        (NEW.id, 'Manager',
            ARRAY['edit_stock', 'view_staff', 'manage_staff', 'manage_roles', 'edit_store_info',
                  'view_restock', 'request_restock']),
        (NEW.id, 'Worker', ARRAY['edit_stock']);
    RETURN NEW;
END $$;
