-- Restock alerts (added after the Gantt tasks): store staff see what's low or out of stock at
-- their store, how popular it is and how often it runs out, and can request a reorder. See
-- app/api/restock.py. Safe to run more than once.

-- Every change to a product's stock at a store, so the app can tell how often it runs out and how
-- fast it sells. Written by a trigger, so staff edits, the product monitor, and the scripts are
-- all recorded however they change stock.
CREATE TABLE IF NOT EXISTS stock_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    store_id INTEGER NOT NULL REFERENCES store_locations (id) ON DELETE CASCADE,
    in_stock BOOLEAN NOT NULL,
    quantity INTEGER,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS stock_events_store_product_idx
    ON stock_events (store_id, product_id, changed_at);

CREATE OR REPLACE FUNCTION record_stock_event() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT'
        OR NEW.in_stock IS DISTINCT FROM OLD.in_stock
        OR NEW.quantity IS DISTINCT FROM OLD.quantity
    THEN
        INSERT INTO stock_events (product_id, store_id, in_stock, quantity)
        VALUES (NEW.product_id, NEW.store_id, NEW.in_stock, NEW.quantity);
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS product_stock_record_event ON product_stock;
CREATE TRIGGER product_stock_record_event
    AFTER INSERT OR UPDATE OF in_stock, quantity ON product_stock
    FOR EACH ROW EXECUTE FUNCTION record_stock_event();

-- Stock that's already there starts its history as of its last update, so e.g. a product that's
-- been out since then counts as out from then on, not from its next change.
INSERT INTO stock_events (product_id, store_id, in_stock, quantity, changed_at)
SELECT ps.product_id, ps.store_id, ps.in_stock, ps.quantity, ps.updated_at
FROM product_stock AS ps
WHERE NOT EXISTS (
    SELECT 1 FROM stock_events AS e
    WHERE e.product_id = ps.product_id AND e.store_id = ps.store_id
);

-- How many times shoppers opened a product's page, or scanned it, each day, at the store they
-- picked in the app (store_id NULL when they hadn't picked one). Anonymous counts only.
CREATE TABLE IF NOT EXISTS product_activity (
    product_id INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    store_id INTEGER REFERENCES store_locations (id) ON DELETE CASCADE,
    day DATE NOT NULL DEFAULT CURRENT_DATE,
    views INTEGER NOT NULL DEFAULT 0 CHECK (views >= 0),
    scans INTEGER NOT NULL DEFAULT 0 CHECK (scans >= 0),
    CONSTRAINT product_activity_one_row_per_day UNIQUE NULLS NOT DISTINCT (product_id, store_id, day)
);

CREATE INDEX IF NOT EXISTS product_activity_store_day_idx ON product_activity (store_id, day);

-- When a product counts as running low at a store: at or below its own reorder point, or the
-- store's default when it has none.
ALTER TABLE store_locations
    ADD COLUMN IF NOT EXISTS default_reorder_point INTEGER NOT NULL DEFAULT 5
    CHECK (default_reorder_point >= 0);

CREATE TABLE IF NOT EXISTS reorder_points (
    product_id INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    store_id INTEGER NOT NULL REFERENCES store_locations (id) ON DELETE CASCADE,
    reorder_point INTEGER NOT NULL CHECK (reorder_point >= 0),
    PRIMARY KEY (product_id, store_id)
);

-- Reorder requests. There are no suppliers yet, so a request is a record of who asked for how
-- many; it closes by itself ("restocked") once the product is above its reorder point again.
CREATE TABLE IF NOT EXISTS restock_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    store_id INTEGER NOT NULL REFERENCES store_locations (id) ON DELETE CASCADE,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    note VARCHAR(200),
    status VARCHAR(20) NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'restocked', 'cancelled')),
    requested_by UUID REFERENCES users (id) ON DELETE SET NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    closed_at TIMESTAMPTZ,
    CHECK ((status = 'open') = (closed_at IS NULL))
);

-- At most one open request per product at a store.
CREATE UNIQUE INDEX IF NOT EXISTS restock_requests_one_open
    ON restock_requests (product_id, store_id) WHERE status = 'open';
CREATE INDEX IF NOT EXISTS restock_requests_store_idx
    ON restock_requests (store_id, requested_at DESC);

-- Closes open requests once stock is back above the reorder point.
CREATE OR REPLACE FUNCTION close_restocked_requests() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    reorder_at INTEGER;
BEGIN
    IF NOT NEW.in_stock THEN
        RETURN NEW;
    END IF;
    SELECT COALESCE(rp.reorder_point, s.default_reorder_point) INTO reorder_at
    FROM store_locations AS s
    LEFT JOIN reorder_points AS rp ON rp.store_id = s.id AND rp.product_id = NEW.product_id
    WHERE s.id = NEW.store_id;
    -- An unknown quantity that's in stock counts as restocked.
    IF NEW.quantity IS NULL OR NEW.quantity > reorder_at THEN
        UPDATE restock_requests SET status = 'restocked', closed_at = NOW()
        WHERE product_id = NEW.product_id AND store_id = NEW.store_id AND status = 'open';
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS product_stock_close_requests ON product_stock;
CREATE TRIGGER product_stock_close_requests
    AFTER INSERT OR UPDATE OF in_stock, quantity ON product_stock
    FOR EACH ROW EXECUTE FUNCTION close_restocked_requests();

