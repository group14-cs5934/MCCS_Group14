-- What jobs/product-monitor (the review agent, T052.6) collects from stores' product pages. These
-- tables are the agent's own: it writes nothing else by default, and the app's tables aren't
-- touched. All of a product's rows are meant to be aggregated later into one overall review.
--
-- Rows name their product by the agent's own ID (product in jobs/product-monitor/products.yaml,
-- e.g. 'starbucks-veranda-blend-k-cup-pods-32-count'), not by barcode, since many product pages
-- don't show one. Linking an ID to the catalog is a separate step, for when the app shows this
-- data. Likewise, source is a plain slug (e.g. 'navy-exchange'), not a store location.

-- One row per review. Reviewers' names are never stored.
CREATE TABLE IF NOT EXISTS agent_reviews (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product VARCHAR(100) NOT NULL,
    source VARCHAR(100) NOT NULL,
    source_url TEXT NOT NULL,
    -- Hash of the review's text and stars, so a review the page shows again on the next run isn't
    -- saved twice. Two shoppers writing exactly the same text and stars count as one.
    review_key VARCHAR(64) NOT NULL,
    -- On a 0-5 scale, whatever scale the source uses; NULL if the review has no star rating.
    stars NUMERIC(2, 1) CHECK (stars BETWEEN 0 AND 5),
    title VARCHAR(200) CHECK (btrim(title) <> ''),
    body VARCHAR(2000) NOT NULL CHECK (btrim(body) <> ''),
    -- The date the source shows for the review, if any.
    reviewed_on DATE,
    -- When the agent first saw the review.
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- Also the index for a product's reviews (product comes first).
    CONSTRAINT agent_reviews_one_per_key UNIQUE (product, source, review_key)
);

-- What a source's page says about all of a product's reviews, including ones it doesn't show. One
-- row per product per source, replaced on each read. A source often has far more reviews than the
-- agent reads, so aggregation needs these totals to weigh sources fairly.
CREATE TABLE IF NOT EXISTS agent_review_summaries (
    product VARCHAR(100) NOT NULL,
    source VARCHAR(100) NOT NULL,
    source_url TEXT NOT NULL,
    -- The product's name on the source's page.
    product_name VARCHAR(200),
    average_stars NUMERIC(3, 2) CHECK (average_stars BETWEEN 0 AND 5),
    review_count INTEGER CHECK (review_count >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (product, source)
);

-- As with the other tables: Supabase exposes public tables through its REST API, so with row level
-- security on and no policies, only the backend and the agent can read or change them.
ALTER TABLE agent_reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE agent_review_summaries ENABLE ROW LEVEL SECURITY;
