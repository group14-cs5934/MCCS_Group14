-- Product ratings (US08) and reviews (US09), each linked to the product and to the user who wrote
-- it. Rows are added by the API for signed-in users only (T072), so users.id always exists: the
-- API adds a user's row on their first signed-in request (migration 004).
--
-- Deleting a product or a user deletes their ratings and reviews too.

-- One star rating per user per product; rating the same product again updates the row
-- (INSERT ... ON CONFLICT (product_id, user_id) DO UPDATE). The product's average and count come
-- from this table (T054).
CREATE TABLE IF NOT EXISTS ratings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    stars SMALLINT NOT NULL CHECK (stars BETWEEN 1 AND 5),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- Also the index for a product's ratings (product_id comes first).
    CONSTRAINT ratings_one_per_user_per_product UNIQUE (product_id, user_id)
);

-- Lets a user's own ratings be listed, and deleting a user find their rows, without a full scan.
CREATE INDEX IF NOT EXISTS ratings_user_id_idx ON ratings (user_id);

-- Written reviews: an optional title and the review text. One review per user per product, like
-- ratings; writing another one edits it. Detailed rules (e.g. minimum length) are checked by the
-- API (T058); these checks only stop empty or oversized rows getting in some other way.
CREATE TABLE IF NOT EXISTS reviews (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(100) CHECK (btrim(title) <> ''),
    body VARCHAR(2000) NOT NULL CHECK (btrim(body) <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT reviews_one_per_user_per_product UNIQUE (product_id, user_id)
);

-- A product's reviews, newest first, a page at a time (GET /products/{id}/reviews, T060):
--   WHERE product_id = %s ORDER BY created_at DESC, id DESC LIMIT %s OFFSET %s
CREATE INDEX IF NOT EXISTS reviews_product_newest_idx
ON reviews (product_id, created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS reviews_user_id_idx ON reviews (user_id);

-- As with users (migration 004): Supabase exposes public tables through its REST API, so with
-- row level security on and no policies, only the backend can read or change these rows. Nobody
-- can post a rating as someone else by calling Supabase directly.
ALTER TABLE ratings ENABLE ROW LEVEL SECURITY;
ALTER TABLE reviews ENABLE ROW LEVEL SECURITY;
