CREATE TABLE IF NOT EXISTS store_locations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(200) NOT NULL UNIQUE,
    address VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS product_stock (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    store_id INTEGER NOT NULL REFERENCES store_locations(id) ON DELETE CASCADE,
    in_stock BOOLEAN NOT NULL DEFAULT FALSE,
    quantity INTEGER CHECK (quantity IS NULL OR quantity >= 0),
    aisle VARCHAR(50),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT product_stock_one_row_per_store_product
        UNIQUE (product_id, store_id),

    CONSTRAINT product_stock_quantity_consistent
        CHECK (
            quantity IS NULL OR (in_stock = (quantity > 0))
        )
);

CREATE INDEX IF NOT EXISTS product_stock_store_id_idx
    ON product_stock (store_id);

ALTER TABLE store_locations ENABLE ROW LEVEL SECURITY;
ALTER TABLE product_stock ENABLE ROW LEVEL SECURITY;
