-- One row per product sync run (T066), so the team (and later the admin sync-status view, T099)
-- can see when each run started and finished, what it did, and what went wrong. Dry runs aren't
-- recorded.
--
--   status     running while it runs, then succeeded (everything saved), partial (some products
--              couldn't be saved), or failed (the source was down or the run crashed; nothing
--              was saved)
--   issues     how many cleaned products had each data issue, e.g. {"no_price": 2}
--   errors     what went wrong, one message per rejected record, failed product, or crash
CREATE TABLE IF NOT EXISTS ingest_runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(50) NOT NULL,
    status TEXT NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'succeeded', 'partial', 'failed')),
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ,
    fetched INTEGER NOT NULL DEFAULT 0 CHECK (fetched >= 0),
    rejected INTEGER NOT NULL DEFAULT 0 CHECK (rejected >= 0),
    inserted INTEGER NOT NULL DEFAULT 0 CHECK (inserted >= 0),
    updated INTEGER NOT NULL DEFAULT 0 CHECK (updated >= 0),
    unchanged INTEGER NOT NULL DEFAULT 0 CHECK (unchanged >= 0),
    failed INTEGER NOT NULL DEFAULT 0 CHECK (failed >= 0),
    issues JSONB NOT NULL DEFAULT '{}',
    errors JSONB NOT NULL DEFAULT '[]',
    -- A finished run has an end time; a running one doesn't.
    CONSTRAINT ingest_runs_finished_when_done
        CHECK ((status = 'running') = (finished_at IS NULL))
);

-- The latest runs first (sync status, stale-data alerts).
CREATE INDEX IF NOT EXISTS ingest_runs_started_at_idx ON ingest_runs (started_at DESC);

-- As with the other tables: only the backend reads or writes these rows.
ALTER TABLE ingest_runs ENABLE ROW LEVEL SECURITY;
